import type { RawReferenceRows } from "../../src/lib/data/mappers";

/* eslint-disable @typescript-eslint/no-explicit-any */
type Row = Record<string, any>;

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const jsonb = (v: unknown) => `${q(JSON.stringify(v ?? []))}::jsonb`;
const textArr = (v: string[] | undefined) =>
  !v || v.length === 0 ? "'{}'::text[]" : `array[${v.map(q).join(", ")}]::text[]`;

function insert(table: string, rows: Row[], cols: { name: string; fmt?: (v: any) => string }[]): string {
  if (rows.length === 0) return "";
  const values = rows
    .map((r) => `  (${cols.map((c) => (c.fmt ? c.fmt(r[c.name]) : q(r[c.name]))).join(", ")})`)
    .join(",\n");
  return `insert into public.${table} (${cols.map((c) => c.name).join(", ")}) values\n${values};\n`;
}

const c = (name: string, fmt?: (v: any) => string) => ({ name, fmt });

/** Idempotent seed: clears reference tables and re-inserts the dataset. */
export function buildSeedSql(raw: RawReferenceRows): string {
  return [
    "-- Generated by scripts/generate-seed-sql.ts from supabase/seed/reference-data.json. Do not edit by hand.",
    "begin;",
    "delete from public.scheme_hospitals;",
    "delete from public.scheme_documents;",
    "delete from public.scheme_eligibility_rules;",
    "delete from public.scheme_treatments;",
    "delete from public.scheme_sources;",
    "delete from public.hospitals;",
    "delete from public.schemes where id not in (select scheme_id from public.scheme_interactions union select scheme_id from public.application_statuses);",
    "delete from public.medical_needs where id not in (select medical_need_id from public.searches);",
    "delete from public.sources where id not in (select source_id from public.scheme_sources);",
    `insert into public.reference_meta (id, version) values (true, ${q(raw.version)}) on conflict (id) do update set version = excluded.version, updated_at = now();`,
    insert("sources", raw.sources, [c("id"), c("title"), c("publisher"), c("url"), c("source_type"), c("published_on"), c("accessed_on"), c("notes")])
      .replace(/;\n$/, "\non conflict (id) do update set title = excluded.title, publisher = excluded.publisher, url = excluded.url, source_type = excluded.source_type, published_on = excluded.published_on, accessed_on = excluded.accessed_on, notes = excluded.notes;\n"),
    insert("medical_needs", raw.medical_needs, [c("id"), c("name"), c("kind"), c("specialty"), c("summary"), c("sort_order")])
      .replace(/;\n$/, "\non conflict (id) do update set name = excluded.name, kind = excluded.kind, specialty = excluded.specialty, summary = excluded.summary, sort_order = excluded.sort_order;\n"),
    insert("schemes", raw.schemes, [
      c("id"), c("official_name"), c("short_name"), c("issuing_authority"), c("scope"), c("applicable_states", textArr),
      c("summary"), c("intended_beneficiaries"), c("benefit_amount_inr"), c("benefit_unit"), c("benefit_mechanism"),
      c("payment_recipient"), c("benefit_details", jsonb), c("patient_costs_note"), c("application_channel"),
      c("application_steps", jsonb), c("application_url"), c("application_url_status"), c("info_url"), c("hospital_directory_url"), c("helpdesk", jsonb),
      c("verification_status"), c("last_verified_on"), c("source_updated_on"), c("uncertainty_notes", textArr), c("is_demo"),
    ]).replace(
      /;\n$/,
      "\non conflict (id) do update set official_name = excluded.official_name, short_name = excluded.short_name, issuing_authority = excluded.issuing_authority, scope = excluded.scope, applicable_states = excluded.applicable_states, summary = excluded.summary, intended_beneficiaries = excluded.intended_beneficiaries, benefit_amount_inr = excluded.benefit_amount_inr, benefit_unit = excluded.benefit_unit, benefit_mechanism = excluded.benefit_mechanism, payment_recipient = excluded.payment_recipient, benefit_details = excluded.benefit_details, patient_costs_note = excluded.patient_costs_note, application_channel = excluded.application_channel, application_steps = excluded.application_steps, application_url = excluded.application_url, application_url_status = excluded.application_url_status, info_url = excluded.info_url, hospital_directory_url = excluded.hospital_directory_url, helpdesk = excluded.helpdesk, verification_status = excluded.verification_status, last_verified_on = excluded.last_verified_on, source_updated_on = excluded.source_updated_on, uncertainty_notes = excluded.uncertainty_notes, is_demo = excluded.is_demo;\n",
    ),
    insert("scheme_sources", raw.scheme_sources, [c("scheme_id"), c("source_id")]),
    insert("scheme_treatments", raw.scheme_treatments, [c("scheme_id"), c("medical_need_id"), c("coverage_level"), c("coverage_note"), c("source_id")]),
    insert("scheme_eligibility_rules", raw.scheme_eligibility_rules, [
      c("id"), c("scheme_id"), c("criterion"), c("definition", jsonb), c("mandatory"), c("any_of_group"), c("official_text"), c("source_id"), c("sort_order"),
    ]),
    insert("scheme_documents", raw.scheme_documents, [c("scheme_id"), c("document"), c("note"), c("source_id"), c("is_provisional"), c("sort_order")]),
    insert("hospitals", raw.hospitals, [
      c("id"), c("name"), c("address_line"), c("city"), c("district"), c("state"), c("pin"), c("latitude"), c("longitude"),
      c("coordinates_note"), c("phone"), c("website"), c("verification_status"), c("last_verified_on"), c("source_id"),
    ]),
    insert("scheme_hospitals", raw.scheme_hospitals, [c("scheme_id"), c("hospital_id"), c("medical_need_id"), c("department"), c("status"), c("source_id"), c("note")]),
    "commit;",
    "",
  ].join("\n");
}
